const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const A = require('./certification/panel-actions.cjs');

module.exports = async h => {
  const checks = [];
  const check = (ok, label, observed) => {
    checks.push({ label, ok: !!ok, observed });
    fs.writeFileSync(path.join(h.out, 'preset-regression.json'), JSON.stringify({ version: h.version, checks }, null, 2));
    assert.ok(ok, label);
  };
  const inspect = selector => h.panel(A.inspectSelector, selector);
  const click = async selector => { await h.panel(A.clickSelector, selector); await h.wait(400); };
  const input = async (selector, value) => { await h.panel(A.inputSelector, { selector, value }); await h.wait(300); };
  const tokens = async () => { await h.action('open-tokens'); await click('[data-tokens-tab="defined"]'); };
  const usage = async id => (await h.send('SP_GET_PRESETS')).presets.find(p => p.id === id).usageCount;
  const changes = async () => (await h.send('SP_GET_CHANGES')).styleChanges;
  await h.navigate(h.base + '/preset-regression');
  await h.send('SP_ACTIVATE');
  await h.panel(A.showDesign);
  await h.select('source');
  await tokens();
  await h.action('add-preset-open');
  const options = await inspect('[data-dm-defined-kind] option');
  check(!options.some(o => o.value === 'motion') && options.some(o => o.value === 'typography'), '8.10 inert motion excluded; typography retained', options);
  await input('[data-dm-defined-kind]', 'typography');
  await input('[data-dm-defined-name]', 'Preset regression typography');
  await h.action('add-preset-save');
  const preset = (await h.send('SP_GET_PRESETS')).presets.find(p => p.name === 'Preset regression typography');
  check(!!preset, 'preset saved via installed panel', preset);
  const baselineUsage = await usage(preset.id);
  check(baselineUsage === 1, 'Defined usage initially counts source only', baselineUsage);
  const rejected = await h.send('SP_SAVE_PRESET', { name: 'Inert motion', kind: 'motion', props: ['transitionDuration', 'animationIterationCount', 'transformOrigin'] });
  check(rejected.ok === false && /No motion styles/.test(rejected.error), 'content save boundary also rejects inert motion', rejected);
  await h.action('close-tokens');
  await h.select('target');
  const originalFont = await h.content(() => getComputedStyle(document.getElementById('target')).fontSize);
  await tokens();
  await click('[data-dm-action="apply-preset"][data-preset-id="' + preset.id + '"]');
  const applied = await changes();
  const gid = applied[0].groupId;
  check(applied.length >= 4 && applied.every(c => c.groupKind === 'preset' && c.groupId === gid), 'applied properties have one preset envelope', applied);
  check(await usage(preset.id) === baselineUsage + 1, 'Defined usage includes applied target', await usage(preset.id));
  await h.action('close-tokens');
  await h.panel(A.showChanges); await h.wait(300);
  const groups = await inspect('[data-dm-toggle-subgroup]');
  check(groups.length === 1 && groups[0].text.includes(preset.name) && !(await inspect('.dm-change-item')).length, '7.13 / 8.11 one named collapsed preset row', groups);
  await click('[data-dm-toggle-subgroup]');
  check((await inspect('.dm-change-item')).length === applied.length, 'explicit expand reveals all preset properties');
  await h.panel(A.showDesign); await h.panel(A.showChanges); await h.wait(300);
  check((await inspect('.dm-change-item')).length === applied.length, 'rerender preserves explicit expansion');
  await click('[data-dm-toggle-subgroup]');
  check(!(await inspect('.dm-change-item')).length, 'explicit collapse hides preset properties');
  await h.panel(A.showDesign);
  await h.send('SP_APPLY_STYLE', { property: 'backgroundColor', value: 'rgb(1, 2, 3)' });
  const sibling = (await changes()).find(c => c.property === 'backgroundColor');
  check(!!sibling && sibling.groupId !== gid, 'unrelated same-element sibling created', sibling);
  await h.panel(A.showChanges); await h.wait(300);
  await click('[data-dm-revert-subgroup="' + gid + '"]');
  const remaining = await changes();
  check(remaining.length === 1 && remaining[0].id === sibling.id, 'subgroup revert removes only preset and preserves sibling', remaining);
  check(await h.content(() => getComputedStyle(document.getElementById('target')).fontSize) === originalFont, 'subgroup revert restores original typography');
  check(await usage(preset.id) === baselineUsage, 'Defined usage returns to source-only after revert', await usage(preset.id));
  await h.panel(A.showDesign); await tokens();
  await click('[data-dm-action="apply-preset"][data-preset-id="' + preset.id + '"]');
  await click('[data-dm-action="unapply-preset"][data-preset-id="' + preset.id + '"]');
  const afterUnapply = await changes();
  check(afterUnapply.length === 1 && afterUnapply[0].id === sibling.id, '8.12 Applied revert preserves sibling too', afterUnapply);
  for (const [property, value] of [['transitionDelay', '1s'], ['transformStyle', 'preserve-3d'], ['backfaceVisibility', 'hidden']]) {
    await h.action('close-tokens');
    await h.content(({ property, value }) => {
      const style = document.getElementById('source').style;
      style.transitionDelay = ''; style.transformStyle = ''; style.backfaceVisibility = '';
      style[property] = value;
    }, { property, value });
    await h.select('source'); await tokens();
    if (!(await inspect('[data-dm-defined-kind]')).length) await h.action('add-preset-open');
    check((await inspect('[data-dm-defined-kind] option')).some(o => o.value === 'motion'), 'meaningful motion remains eligible: ' + property);
  }
  console.log(JSON.stringify({ pass: checks.length, version: h.version }));
};
